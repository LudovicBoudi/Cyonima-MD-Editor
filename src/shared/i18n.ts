const DICTIONARIES: Record<Language, Dictionary> = { fr, en }

export type TranslationParams = Record<string, string | number>

/** Replaces `{name}` placeholders with their values, leaving unknown ones. */
export function interpolate(template: string, params?: TranslationParams): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match
  )
}

export function translate(
  language: Language,
  key: TranslationKey,
  params?: TranslationParams
): string {
  return interpolate(DICTIONARIES[language][key] ?? fr[key] ?? key, params)
}

export type Translator = (key: TranslationKey, params?: TranslationParams) => string

export function createTranslator(language: Language): Translator {
  return (key, params) => translate(language, key, params)
}

/** Selects the singular or plural key for a count. */
export function pluralKey(one: TranslationKey, other: TranslationKey, count: number): TranslationKey {
  return count === 1 ? one : other
}
