import type { Language, LanguagePreference } from './types'

/** Language used when the system language is neither French nor English. */
export const DEFAULT_LANGUAGE: Language = 'fr'

/**
 * Resolves the language actually displayed. `system` follows the operating
 * system, but only French and English are translated: anything else falls back
 * to French, the application's original language.
 */
export function resolveLanguage(
  preference: LanguagePreference,
  systemLocale: string | null | undefined
): Language {
  if (preference === 'fr' || preference === 'en') return preference
  const primary = (systemLocale ?? '').toLowerCase().split(/[-_]/)[0]
  if (primary === 'en') return 'en'
  return DEFAULT_LANGUAGE
}

/** BCP 47 tag used for dates, numbers and exported documents. */
export function localeTag(language: Language, systemLocale?: string | null): string {
  const primary = (systemLocale ?? '').toLowerCase().split(/[-_]/)[0]
  if (systemLocale && primary === language) return systemLocale
  return language === 'fr' ? 'fr-FR' : 'en-US'
}

/** Text direction of a supported language; both are left-to-right today. */
export function languageDirection(_language: Language): 'ltr' {
  return 'ltr'
}

